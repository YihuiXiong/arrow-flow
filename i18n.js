function t(source, values = {}) {
  let result = document.getElementById('language')?.value === 'en' ? (EN[source] ?? source) : source;
  result = result.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
  return result.replace(/\b1 sets\b/g, '1 set').replace(/\b1 rounds\b/g, '1 round');
}
// Keep original text nodes so switching languages preserves icons and markup.
const languageNodes = [];
const languageWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (languageWalker.nextNode()) {
  const node = languageWalker.currentNode;
  if (/[\u4e00-\u9fff]/.test(node.nodeValue) && !['SCRIPT', 'STYLE'].includes(node.parentElement?.tagName)) {
    languageNodes.push([node, node.nodeValue]);
  }
}
const languageAttributes = [...document.querySelectorAll('[aria-label]')]
  .filter(el => /[\u4e00-\u9fff]/.test(el.getAttribute('aria-label')))
  .map(el => [el, el.getAttribute('aria-label')]);
function applyStaticLanguage() {
  const english = document.getElementById('language').value === 'en';
  document.documentElement.lang = english ? 'en' : 'zh-CN';
  document.title = t('箭头反应 · Arrow Flow');
  for (const [node, source] of languageNodes) {
    if (node.isConnected) node.nodeValue = source.replace(source.trim(), t(source.trim()));
  }
  for (const [el, source] of languageAttributes) el.setAttribute('aria-label', t(source));
}
